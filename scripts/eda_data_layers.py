"""EDA: layer A (SSI DailyStockPrice, 2020+) vs layer B (vnstock refetch, 2013+).

Answers which start date the thesis should use. Writes:
    docs/eda/data-layers.md                 tables + numbers quoted in the report
    report/figures/data_coverage.png         stocks per year in each layer
    report/figures/data_vnindex_regimes.png  VNINDEX with the period each layer covers

    python scripts/eda_data_layers.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import polars as pl  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
FIG = ROOT / "report" / "figures"
OUT_MD = ROOT / "docs" / "eda" / "data-layers.md"
GAP_PCT = -11.0          # below the -7% HOSE band: cannot be an ordinary session


def md_table(df: pl.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(f"{v:,.4g}" if isinstance(v, float) else str(v) for v in r) + " |"
            for r in df.iter_rows()]
    return "\n".join([head, sep, *rows])


def gap_steps(df: pl.DataFrame, open_col: str, close_col: str) -> pl.DataFrame:
    """Open-vs-previous-close gaps beyond the daily band = adjustment seams or real CA steps."""
    return (
        df.sort(["ticker", "date"])
        .with_columns(((pl.col(open_col) / pl.col(close_col).shift(1).over("ticker") - 1) * 100).alias("gap"))
        .filter(pl.col("gap") < GAP_PCT)
    )


def main() -> None:
    a_all = pl.read_parquet(DATA / "hose_daily_ssi.parquet")
    a = a_all.filter((pl.col("instrument") == "stock") & (pl.col("close") > 0))
    b = pl.read_parquet(DATA / "hose_daily_vci.parquet").filter(pl.col("ticker").str.len_chars() == 3)
    idx = pl.read_parquet(DATA / "index_daily.parquet").filter(pl.col("index_id") == "VNINDEX")
    out: list[str] = ["# EDA — data layers A vs B", "",
                      f"Generated by `scripts/eda_data_layers.py`. Layer A basis date: "
                      f"{a_all['basis_date'][0]}. Layer B basis date: 2026-10-18 (parent refetch).", ""]

    # 1. coverage --------------------------------------------------------------------------
    last_a = a["date"].max()
    a_tickers = set(a["ticker"].unique().to_list())
    live_a = set(a.filter(pl.col("date") == last_a)["ticker"].to_list())
    b_tickers = set(b["ticker"].unique().to_list())
    summary = pl.DataFrame({
        "layer": ["A (SSI)", "B (VCI refetch)"],
        "start": [str(a["date"].min()), str(b["date"].min())],
        "end": [str(last_a), str(b["date"].max())],
        "stock_rows": [a.height, b.height],
        "tickers": [len(a_tickers), len(b_tickers)],
        "raw_prices": ["yes", "no"],
        "ref/ceiling/floor": ["yes", "no"],
        "foreign_flow": ["yes", "no"],
    })
    out += ["## 1. Coverage", "", md_table(summary), ""]
    gone = sorted(a_tickers - live_a)
    missing_in_b = sorted(a_tickers - b_tickers)
    out += [f"- Stocks in A that stopped trading before {last_a} (delisted / moved exchange): "
            f"**{len(gone)}** — present in A by construction.",
            f"- Stocks in A absent from B: **{len(missing_in_b)}** "
            f"({len(set(missing_in_b) & set(gone))} of them are the delisted ones) → B is "
            "survivorship-biased: it only holds names still listed when it was fetched.", ""]

    per_year = (
        pl.concat([
            a.select(pl.col("date").dt.year().alias("year"), "ticker").unique().with_columns(pl.lit("A").alias("layer")),
            b.select(pl.col("date").dt.year().alias("year"), "ticker").unique().with_columns(pl.lit("B").alias("layer")),
        ])
        .group_by("year", "layer").len().sort("year")
        .pivot(on="layer", index="year", values="len").sort("year")
    )
    out += ["Stocks with at least one bar per year:", "", md_table(per_year), ""]

    def completeness(df: pl.DataFrame, name: str) -> dict[str, object]:
        """Bars per stock / exchange sessions between its first and last bar."""
        sessions = df["date"].unique().sort()
        span = df.group_by("ticker").agg(pl.len().alias("bars"), pl.col("date").min().alias("lo"),
                                          pl.col("date").max().alias("hi"))
        cnt = [int(((sessions >= lo) & (sessions <= hi)).sum()) for lo, hi in span.select("lo", "hi").iter_rows()]
        ratio = span["bars"] / pl.Series(cnt)
        return {"layer": name, "median": float(ratio.median()), "p5": float(ratio.quantile(0.05)),
                "stocks <95%": int((ratio < 0.95).sum()), "stocks": span.height}
    out += ["Bar completeness (bars per stock / exchange sessions inside its own first..last span; "
            "1.0 = no missing session, values < 1 are suspensions or data holes):", "",
            md_table(pl.DataFrame([completeness(a, "A"), completeness(b, "B")])), ""]

    # 1b. row quality (A) --------------------------------------------------------------------
    novol = a.filter(pl.col("match_vol").fill_null(0) == 0)
    noref = a.filter(pl.col("ref_price") <= 0)
    out += ["## 1b. Row quality in A", "",
            md_table(pl.DataFrame({
                "check": ["zero-volume rows", "zero-volume rows whose OHLC is not flat",
                          "rows with ref_price <= 0", "  of which traded",
                          "tickers with ref_price <= 0 on every row"],
                "rows": [novol.height,
                         novol.filter((pl.col("high") != pl.col("low")) | (pl.col("open") != pl.col("close"))).height,
                         noref.height, noref.filter(pl.col("match_vol") > 0).height,
                         int((a.group_by("ticker").agg((pl.col("ref_price") <= 0).all().alias("x"))["x"]).sum())],
            })), "",
            f"- Zero-volume rows are {novol.height / a.height:.1%} of stock rows. SSI fills their "
            "OHLC with placeholder values (often open near the floor, close at a stale level), so "
            "they must be flagged as non-trading sessions and their OHLC discarded — otherwise each "
            "one prints a fake band-wide bar that a detector reads as a climax.", ""]
    a = a.filter(pl.col("match_vol") > 0)   # everything below uses traded sessions only

    # 2. overlap agreement -----------------------------------------------------------------
    j = (
        a.select("ticker", "date", "close", "close_adj").join(
            b.select("ticker", "date", pl.col("close_adj").alias("close_adj_b")), on=["ticker", "date"])
        .with_columns(((pl.col("close_adj_b") / pl.col("close_adj") - 1) * 100).alias("diff_pct"))
    )
    per_tkr = j.group_by("ticker").agg(pl.col("diff_pct").abs().median().alias("med_abs_diff_pct"))
    agree = pl.DataFrame({
        "overlap_rows": [j.height],
        "rows |diff|<0.5%": [float((j["diff_pct"].abs() < 0.5).mean())],
        "rows |diff|<2%": [float((j["diff_pct"].abs() < 2.0).mean())],
        "tickers median|diff|>2%": [int((per_tkr["med_abs_diff_pct"] > 2.0).sum())],
    })
    by_year = j.group_by(pl.col("date").dt.year().alias("year")).agg(
        pl.len().alias("rows"),
        ((pl.col("close_adj_b") / pl.col("close") - 1).abs() < 0.005).mean().alias("B≈A raw"),
        ((pl.col("diff_pct")).abs() < 0.5).mean().alias("B≈A adjusted"),
        (pl.col("close_adj_b") / pl.col("close_adj")).median().alias("median B/A adjusted"),
    ).sort("year")
    out += ["## 2. Agreement on the overlap (2020+, adjusted close, A vs B, traded sessions)", "",
            md_table(agree), "", "By year (|diff| < 0.5%):", "", md_table(by_year), "",
            "The median ratio stays at ~1.00 every year, yet agreement falls going back in time: "
            "B also adjusts small corporate actions (cash dividends) that SSI's "
            "`ClosePriceAdjusted` leaves out, and each one shifts all earlier B prices by a few "
            "percent.", ""]

    # 3. steps -----------------------------------------------------------------------------
    steps_a_raw = gap_steps(a, "open", "close")
    steps_a_adj = gap_steps(a.with_columns(pl.col("open_adj")), "open_adj", "close_adj")
    steps_b = gap_steps(b, "open_adj", "close_adj")
    a_ref = a.filter(pl.col("ref_price") > 0).sort(["ticker", "date"]).with_columns(
        (pl.col("adj_factor") / pl.col("adj_factor").shift(1).over("ticker") - 1).abs().alias("dfac"),
        (pl.col("ref_price") / pl.col("close").shift(1).over("ticker")).alias("ref_ratio"))
    ca_days = a_ref.filter(pl.col("dfac") > 0.005)
    ex_big = a_ref.filter(pl.col("ref_ratio") < 0.89)    # exchange set the reference >11% below
    ex_big_adj = ex_big.filter(pl.col("dfac") > 0.005)
    out += ["## 3. Price steps beyond the -7% band (gap < -11%)", "",
            md_table(pl.DataFrame({
                "series": ["A raw", "A adjusted (SSI)", "B adjusted, all years", "B adjusted, 2020+"],
                "steps": [steps_a_raw.height, steps_a_adj.height, steps_b.height,
                          steps_b.filter(pl.col("date").dt.year() >= 2020).height],
            })), "",
            f"- Corporate-action days detected in A from a change in `adj_factor`: **{ca_days.height}**.",
            f"- Sessions where the exchange set the reference price >11% below the previous close "
            f"(a large ex-right): **{ex_big.height}**, of which SSI's adjusted close absorbs "
            f"**{ex_big_adj.height}**. Where SSI does adjust, the factor step falls on the ex-date "
            "itself; where it does not, the drop survives in the adjusted series.",
            "- Raw-series steps are real ex-right drops; on a correct adjusted series they should "
            "vanish. Steps left on an adjusted series are basis seams that a Wyckoff detector would "
            "misread as climaxes.", ""]

    # 4. limit locks -----------------------------------------------------------------------
    locks = (
        a.group_by(pl.col("date").dt.year().alias("year"))
        .agg((pl.col("at_ceiling").mean() * 100).alias("pct_ceiling"),
             (pl.col("at_floor").mean() * 100).alias("pct_floor"))
        .sort("year")
    )
    out += ["## 4. Limit-lock frequency (A only — B cannot measure it)", "", md_table(locks), "",
            "Share of stock-sessions closing on the ceiling / floor: orders there may not fill, "
            "so stop-losses can slip by a full band. Only layer A lets the backtest model this "
            "from the exchange's own limit prices.", ""]

    # 5. regimes ---------------------------------------------------------------------------
    ix = idx.sort("date").with_columns(pl.col("index_value").cum_max().alias("peak"))
    ix = ix.with_columns(((pl.col("index_value") / pl.col("peak") - 1) * 100).alias("dd"))
    regimes = [("2018 correction", "2018-04-01", "2019-01-31"), ("2020 COVID crash", "2020-01-15", "2020-04-30"),
               ("2022 bear market", "2022-04-01", "2022-11-30"), ("2023-26", "2023-01-01", str(ix["date"].max()))]
    rows = []
    for name, s, e in regimes:
        w = ix.filter(pl.col("date").is_between(pl.lit(s).str.to_date(), pl.lit(e).str.to_date()))
        hi = w["index_value"].max()
        lo = w.filter(pl.col("date") >= w.filter(pl.col("index_value") == hi)["date"][0])["index_value"].min()
        rows.append((name, s, e, float((lo / hi - 1) * 100), "B only" if e < "2020-01-01" else "A and B"))
    out += ["## 5. Market regimes covered (VNINDEX peak-to-trough inside each window)", "",
            md_table(pl.DataFrame(rows, schema=["regime", "from", "to", "drawdown_pct", "layers"], orient="row")), ""]

    # figures ------------------------------------------------------------------------------
    FIG.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(8, 3.6))
    py = per_year.to_pandas()
    ax.bar(py["year"] - 0.2, py["B"].fillna(0), width=0.4, label="B: vnstock refetch (adjusted only)")
    ax.bar(py["year"] + 0.2, py["A"].fillna(0), width=0.4, label="A: SSI DailyStockPrice")
    ax.set_xlabel("year"); ax.set_ylabel("HOSE stocks with data"); ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(FIG / "data_coverage.png", dpi=200); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.6))
    pdx = ix.to_pandas()
    ax.plot(pdx["date"], pdx["index_value"], lw=0.8, color="black")
    ax.axvspan(b["date"].min(), b["date"].max(), color="tab:blue", alpha=0.08, label="layer B")
    ax.axvspan(a["date"].min(), a["date"].max(), color="tab:orange", alpha=0.15, label="layer A")
    ax.set_ylabel("VNINDEX"); ax.legend(frameon=False, loc="upper left")
    fig.tight_layout(); fig.savefig(FIG / "data_vnindex_regimes.png", dpi=200); plt.close(fig)

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
