"""EDA on the cleaned series: which stocks should the models learn from?

    python scripts/eda_universe.py

Writes docs/eda/universe.md and three report figures:
    report/figures/universe_concentration.png   share of traded value held by the top N stocks
    report/figures/universe_returns.png         daily return distribution, liquid vs thin
    report/figures/universe_corr.png            return correlation matrix of the 30 most traded stocks

All liquidity ranks are the cleaned series' lagged ranks (`adv_rank`), so membership on a day uses
only earlier sessions.
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import polars as pl  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "report" / "figures"
OUT_MD = ROOT / "docs" / "eda" / "universe.md"
TOP_NS = (30, 50, 100, 150, 200, 300)
LIQUID_N = 150


def md_table(df: pl.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(f"{v:,.4g}" if isinstance(v, float) else str(v) for v in r) + " |"
            for r in df.iter_rows()]
    return "\n".join([head, sep, *rows])


def main() -> None:
    c = pl.read_parquet(ROOT / "data" / "hose_daily_clean.parquet").sort("ticker", "date")
    c = c.with_columns((pl.col("close_adj") / pl.col("close_adj").shift(1).over("ticker") - 1).alias("ret"))
    traded = c.filter(pl.col("is_traded") & ~pl.col("price_suspect"))
    out = ["# EDA — which stocks to learn from", "",
           f"Generated by `scripts/eda_universe.py` on `data/hose_daily_clean.parquet` "
           f"({c['date'].min()}..{c['date'].max()}, {c['ticker'].n_unique()} stocks).", ""]

    # 1. concentration of traded value ---------------------------------------------------------
    ranked = traded.with_columns(
        pl.col("match_val").rank("ordinal", descending=True).over("date").alias("same_day_rank"))
    day_total = ranked.group_by("date").agg(pl.col("match_val").sum().alias("tot"))
    conc = []
    for n in TOP_NS:
        share = ranked.filter(pl.col("same_day_rank") <= n).group_by("date").agg(
            pl.col("match_val").sum().alias("v")).join(day_total, on="date").with_columns(
            (pl.col("v") / pl.col("tot")).alias("s"))["s"]
        conc.append((n, float(share.median()), float(share.quantile(0.1))))
    conc_df = pl.DataFrame(conc, schema=["top_n", "median share of value", "p10 share"], orient="row")
    out += ["## 1. How concentrated is trading?", "",
            "Share of each day's matched value traded in the N most traded stocks that day.", "",
            md_table(conc_df), ""]

    # 2. universe stability ----------------------------------------------------------------------
    liq = c.filter(pl.col("is_liquid"))
    members = liq.group_by("date").agg(pl.col("ticker")).sort("date")
    sets = [set(x) for x in members["ticker"].to_list()]
    churn = [len(sets[i] - sets[i - 1]) for i in range(1, len(sets))]
    ever = liq["ticker"].unique()
    last_day = c["date"].max()
    alive = set(c.filter(pl.col("date") == last_day)["ticker"].to_list())
    gone_liquid = [t for t in ever.to_list() if t not in alive]
    tenure = liq.group_by("ticker").len()["len"]
    out += [f"## 2. The top-{LIQUID_N} universe over time", "",
            md_table(pl.DataFrame({
                "measure": ["stocks ever in the universe", "  of which no longer listed on the last day",
                            "median sessions a member stays in", "new members per session (median)",
                            "new members per session (p95)", "stocks never in the universe"],
                "value": [ever.len(), len(gone_liquid), int(tenure.median()), int(np.median(churn)),
                          int(np.quantile(churn, 0.95)), c["ticker"].n_unique() - ever.len()],
            })), "",
            f"Delisted names that were liquid at some point: {', '.join(sorted(gone_liquid)) or 'none'}. "
            "Picking today's liquid names and backtesting them over the past would drop these — the "
            "universe must be chosen day by day.", ""]

    # 3. data quality and tradability, liquid vs thin --------------------------------------------
    ranked_any = c.filter(pl.col("adv_rank").is_not_null()).with_columns(
        pl.when(pl.col("adv_rank") <= 50).then(pl.lit("1 top 50"))
        .when(pl.col("adv_rank") <= LIQUID_N).then(pl.lit(f"2 top 51-{LIQUID_N}"))
        .when(pl.col("adv_rank") <= 300).then(pl.lit(f"3 {LIQUID_N + 1}-300"))
        .otherwise(pl.lit("4 beyond 300")).alias("bucket"))
    qual = ranked_any.group_by("bucket").agg(
        pl.len().alias("stock-sessions"),
        ((~pl.col("is_traded")).mean() * 100).alias("% no trade"),
        (pl.col("at_ceiling").mean() * 100).alias("% at ceiling"),
        (pl.col("at_floor").mean() * 100).alias("% at floor"),
        (pl.col("adv_vnd").median() / 1e9).alias("median value, bn VND"),
        (pl.col("ret").abs().median() * 100).alias("median |return| %"),
    ).sort("bucket")
    out += ["## 3. Quality and tradability by liquidity bucket", "", md_table(qual), ""]

    # 4. return distribution -----------------------------------------------------------------------
    r_liq = liq.filter(pl.col("ret").is_not_null())["ret"].to_numpy()
    r_thin = c.filter(~pl.col("is_liquid") & pl.col("adv_rank").is_not_null() & pl.col("ret").is_not_null())["ret"].to_numpy()

    def describe(r: np.ndarray, name: str) -> dict[str, object]:
        m, s = r.mean(), r.std()
        return {"group": name, "n": len(r), "mean %": m * 100, "std %": s * 100,
                "skew": float(((r - m) ** 3).mean() / s ** 3), "excess kurtosis": float(((r - m) ** 4).mean() / s ** 4 - 3),
                "share |r| > 3 std %": float((np.abs(r - m) > 3 * s).mean() * 100)}
    out += ["## 4. Daily returns (back-adjusted close to close)", "",
            md_table(pl.DataFrame([describe(r_liq, f"top {LIQUID_N}"), describe(r_thin, "rest")])), "",
            "A normal distribution has excess kurtosis 0 and about 0.27% of days beyond 3 standard "
            "deviations.", ""]

    # 5. correlation ------------------------------------------------------------------------------
    top30 = (c.filter(pl.col("date") == last_day).sort("adv_rank").head(30)["ticker"].to_list())
    wide = (liq.filter(pl.col("ticker").is_in(top30)).pivot(on="ticker", index="date", values="ret")
            .sort("date").drop("date"))
    wide = wide.select([t for t in top30 if t in wide.columns])
    corr = wide.to_pandas().corr(min_periods=250)
    off = corr.values[~np.eye(len(corr), dtype=bool)]
    yearly = []
    for y, g in liq.filter(pl.col("ret").is_not_null()).group_by(pl.col("date").dt.year().alias("y")):
        w = g.pivot(on="ticker", index="date", values="ret").drop("date").to_pandas()
        w = w.loc[:, w.notna().mean() > 0.9]
        cm = w.corr().values
        yearly.append((int(y[0]), int(w.shape[1]), float(np.nanmean(cm[~np.eye(len(cm), dtype=bool)]))))
    out += ["## 5. Co-movement", "",
            f"Mean pairwise correlation of daily returns among today's 30 most traded stocks: "
            f"**{np.nanmean(off):.2f}** (min {np.nanmin(off):.2f}, max {np.nanmax(off):.2f}).", "",
            "Mean pairwise correlation inside the liquid universe, by year (stocks present on >90% of sessions):", "",
            md_table(pl.DataFrame(sorted(yearly), schema=["year", "stocks", "mean corr"], orient="row")), ""]

    # figures ---------------------------------------------------------------------------------------
    FIG.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(7, 3.4))
    ax.plot([n for n, *_ in conc], [m * 100 for _, m, _ in conc], marker="o", color="tab:blue", label="median day")
    ax.plot([n for n, *_ in conc], [p * 100 for *_, p in conc], marker="o", ls="--", color="tab:gray", label="10th percentile day")
    ax.axvline(LIQUID_N, color="tab:orange", lw=0.8)
    ax.set_xlabel("N most traded stocks that day"); ax.set_ylabel("share of matched value (%)")
    ax.set_ylim(0, 100); ax.legend(frameon=False); fig.tight_layout()
    fig.savefig(FIG / "universe_concentration.png", dpi=200); plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 3.4))
    bins = np.linspace(-0.08, 0.08, 81)
    ax.hist(r_liq, bins=bins, density=True, alpha=0.6, label=f"top {LIQUID_N}")
    ax.hist(r_thin, bins=bins, density=True, alpha=0.5, label="rest")
    ax.set_yscale("log"); ax.set_xlabel("daily return"); ax.set_ylabel("density (log)")
    ax.legend(frameon=False); fig.tight_layout()
    fig.savefig(FIG / "universe_returns.png", dpi=200); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.4, 5.6))
    im = ax.imshow(corr.values, vmin=-1, vmax=1, cmap="RdBu_r")
    ax.set_xticks(range(len(corr))); ax.set_xticklabels(corr.columns, rotation=90, fontsize=6)
    ax.set_yticks(range(len(corr))); ax.set_yticklabels(corr.columns, fontsize=6)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04); fig.tight_layout()
    fig.savefig(FIG / "universe_corr.png", dpi=200); plt.close(fig)

    OUT_MD.write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
