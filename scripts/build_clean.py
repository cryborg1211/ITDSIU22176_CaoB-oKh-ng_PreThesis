"""Build data/hose_daily_clean.parquet from layer A and measure the result.

    python scripts/build_clean.py

Writes docs/eda/clean-validation.md. Layer B is used only as an independent check of the
ex-right dates, never as an input, so the agreement figure is not circular.
"""
from __future__ import annotations

import sys
from pathlib import Path

import polars as pl

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from wyckoff.data.clean import CleanConfig, clean_layer_a  # noqa: E402

DATA = ROOT / "data"
OUT_MD = ROOT / "docs" / "eda" / "clean-validation.md"
GAP = -0.11             # open vs previous close, beyond the -7% band


def md_table(df: pl.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(f"{v:,.4g}" if isinstance(v, float) else str(v) for v in r) + " |"
            for r in df.iter_rows()]
    return "\n".join([head, sep, *rows])


def gaps(df: pl.DataFrame, open_col: str, close_col: str, liquid: pl.DataFrame) -> tuple[int, int]:
    """Bars opening below the band relative to the previous close: all stocks, liquid sessions."""
    t = (
        df.filter(pl.col(close_col).is_not_null() & (pl.col(close_col) > 0) & (pl.col(open_col) > 0))
        .sort("ticker", "date")
        .with_columns((pl.col(open_col) / pl.col(close_col).shift(1).over("ticker") - 1).alias("_g"))
        .filter(pl.col("_g") < GAP)
    )
    return t.height, t.join(liquid, on=["ticker", "date"]).height


def main() -> None:
    cfg = CleanConfig()
    a = pl.read_parquet(DATA / "hose_daily_ssi.parquet")
    b = pl.read_parquet(DATA / "hose_daily_vci.parquet")
    c = clean_layer_a(a, cfg)
    c.write_parquet(DATA / "hose_daily_clean.parquet")

    stocks = a.filter(pl.col("instrument") == "stock")
    out = ["# Validation of the cleaned series", "",
           "Generated by `scripts/build_clean.py`. Universe: HOSE stocks, "
           f"{c['date'].min()}..{c['date'].max()}. Liquid = top {cfg.liquid_top_n} by trailing "
           f"{cfg.adv_window}-session median matched value, lagged one session.", ""]

    out += ["## Row accounting", "", md_table(pl.DataFrame({
        "step": ["stock rows in layer A", "dropped: close <= 0 (never traded) or before start",
                 "kept", "non-trading (zero matched volume)", "price suspect (non-tick OHLC)",
                 "limit prices unknown", "usable priced bars", "usable and liquid"],
        "rows": [stocks.height, stocks.height - c.height, c.height, int((~c["is_traded"]).sum()),
                 int(c["price_suspect"].sum()), int((~c["limit_known"]).sum()),
                 int(c["close"].is_not_null().sum()),
                 int((c["close"].is_not_null() & c["is_liquid"]).sum())],
    })), "", f"Stocks kept: {c['ticker'].n_unique()}. Stocks with the suspect flag: "
             f"{c.filter(pl.col('price_suspect'))['ticker'].unique().sort().to_list()}.", ""]

    # gaps per series, over one common period
    start = c["date"].min()
    a_traded = stocks.filter((pl.col("match_vol") > 0) & (pl.col("close") > 0) & (pl.col("date") >= start))
    liquid = c.filter(pl.col("is_liquid")).select("ticker", "date")
    b_p = b.filter(pl.col("date") >= start)
    rows = [
        ("A raw", *gaps(a_traded, "open", "close", liquid)),
        ("A SSI adjusted", *gaps(a_traded, "open_adj", "close_adj", liquid)),
        ("B adjusted", *gaps(b_p, "open_adj", "close_adj", liquid)),
        ("Clean", *gaps(c, "open_adj", "close_adj", liquid)),
    ]
    out += ["## Opening gaps below -11% (not possible inside the band without a corporate action)", "",
            md_table(pl.DataFrame(rows, schema=["series", "all stocks", "liquid"], orient="row")), ""]

    # ex-right events against layer B, which never feeds the clean series
    ev = c.filter(pl.col("ex_source").is_not_null())
    bf = b.sort("ticker", "date").select("ticker", "date", pl.col("close_adj").alias("cb"))
    j = c.join(bf, on=["ticker", "date"], how="inner").sort("ticker", "date").with_columns(
        (pl.col("cb") / pl.col("close")).alias("bfac")).filter(pl.col("bfac").is_not_null()).with_columns(
        (pl.col("bfac") / pl.col("bfac").shift(1).over("ticker")).alias("bstep"))
    chk = j.filter(pl.col("ex_source").is_not_null() & pl.col("bstep").is_not_null()).with_columns(
        ((pl.col("ex_ratio") * pl.col("bstep") - 1).abs() < 0.01).alias("match_b"))
    by_src = ev.group_by("ex_source").len().join(
        chk.group_by("ex_source").agg(pl.len().alias("checked"), pl.col("match_b").mean().alias("match_B")),
        on="ex_source", how="left").sort("ex_source")
    ssi_steps = c.with_columns(
        (pl.col("ssi_adj_factor") / pl.col("ssi_adj_factor").shift(1).over("ticker") - 1).abs().alias("_s")
    ).filter(pl.col("ex_source").is_not_null() & (pl.col("_s") > cfg.ssi_step_min)).height
    out += ["## Ex-right events accepted", "", md_table(by_src), "",
            f"Total {ev.height} events; SSI's own factor steps on {ssi_steps} of them. `match_B` = layer "
            "B's own factor steps by the same ratio on the same date, within 1%.", ""]

    # bucket health, cross-section, sanity
    tr = c.filter(pl.col("close").is_not_null())
    bad_ohlc = tr.filter(pl.col("ohlc_repaired"))
    out_band = tr.filter(pl.col("limit_known") & ((pl.col("close") > pl.col("ceiling_price")) | (pl.col("close") < pl.col("floor_price"))))
    per_day = c.group_by("date").agg(pl.col("is_traded").sum().alias("traded"), pl.len().alias("rows"))
    out += ["## Sanity", "", md_table(pl.DataFrame({
        "check": ["bars repaired (high/low not containing open/close, or open = 0)", "  of which liquid",
                  "bars closing outside the session's limits", "  of which liquid",
                  "fewest stocks traded in one session", "median stocks traded per session"],
        "value": [bad_ohlc.height, int(bad_ohlc["is_liquid"].sum()), out_band.height, int(out_band["is_liquid"].sum()),
                  int(per_day["traded"].min()), int(per_day["traded"].median())],
    })), ""]
    locks = c.filter(pl.col("is_liquid")).group_by(pl.col("date").dt.year().alias("year")).agg(
        (pl.col("at_ceiling").mean() * 100).alias("pct_ceiling"), (pl.col("at_floor").mean() * 100).alias("pct_floor")).sort("year")
    out += ["## Limit locks on liquid names", "", md_table(locks), ""]

    OUT_MD.write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
